// ============================================================
// ISettingsSource.cs - 设置存储源的统一接口
// 功能：抽象一张「按键取放的字符串配置表」，让设置项门面不关心底层是 JSON 文件还是别的介质
// 设计理念：接口只认字符串，序列化格式与落盘细节都留在实现类里，换存储方式时上层不用改
// 编译：build.cmd（详见 编译说明.md）
// ============================================================

namespace FortyOne.AudioSwitcher.Configuration
{
    public interface ISettingsSource
    {
        // ===================== 生命周期 =====================
        // 指定配置文件的落盘位置  参数：文件完整路径  返回：无
        void SetFilePath(string path);
        // 从磁盘读入配置  参数：无  返回：无
        // 读取失败由实现类自行兜底：加载设置是启动路径上的一步，不能因为一个坏文件让程序起不来
        void Load();
        // 把内存中的配置整体写回磁盘  参数：无  返回：无
        void Save();

        // ===================== 键值读写 =====================
        // 按键取值  参数：键名  返回：值；键不存在时返回空字符串而不是 null
        // 约定不返回 null，调用方可以直接参与字符串比较，省掉一层层判空
        string Get(string key);
        // 按键写值并立即持久化  参数：键名、值  返回：无
        void Set(string key, string value);

        // 判断某个键是否已经写过  参数：键名  返回：存在为 true
        // 与 Get 返回空串区分开：只有靠它才能分辨「没配过」和「配成空值」，补默认值时要用
        bool Contains(string key);
    }
}
